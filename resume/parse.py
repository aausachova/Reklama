vacancies = []

for id in IDs[:50]:
    url = f"https://technomoscow.ru/tech-work/detail.php?ID={id}"
    try:
        response = requests.get(url)
    except:
        continue
    response.encoding = "utf-8"  # чтобы корректно обрабатывалась кириллица

    soup = BeautifulSoup(response.text, "html.parser")

    requirements_block = None
    for block in soup.find_all("div", class_="modal__card-duties"):
        title = block.find("div", class_="modal__duties-name")
        if title and "ТРЕБОВАНИЯ" in title.get_text(strip=True).upper():
            requirements_block = block
            break
    items = [li.get_text(strip=True) for li in requirements_block.find_all("li")]

    name = soup.select_one('.modal__card-name').get_text(strip=True)
    vacancies.append({
        "name": name,
        "requirements": items,
        "id": id
    })
    if name == "":
        continue

with open('vacancies.json', 'w', encoding='utf-8') as f:
    json.dump(vacancies, f, ensure_ascii=False, indent=4)
